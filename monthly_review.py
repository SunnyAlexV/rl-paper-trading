"""Monthly health and performance review of the paper fleet (read-only; changes nothing).

    python3 -W ignore monthly_review.py [--month YYYY-MM]      (default: the previous calendar month)

Writes reports/monthly/<YYYY-MM>.md with the numbers only (the scheduled review adds the assessment):
  1. Is it running? trading days with an NSE price file vs days each account recorded; missing days; integrity check.
  2. Results: month and since-start post-tax returns, max drawdown, vs Nifty 50 / Nifty 500 (price indices).
  3. The primary against the verdict thresholds fixed in PREREGISTRATION.md (27 Nov 2026, "new primary test").
  4. Post-trade: trades closed in the month, diagnoses, candidate hypotheses from the learning ledger.
"""
import argparse, glob, json, os, sys
import numpy as np, pandas as pd
sys.path.insert(0, ".")
PRIMARY = "paper_mdeliv_10L"


def month_bounds(m):
    p = pd.Period(m, "M"); return p.start_time, p.end_time.normalize()


def idx_ret(ix, col, a, b, start=None):
    """Index return over the month [a, b]; if the account started inside the month, from its first day's close."""
    s = ix[col].dropna()
    if start is not None and start > a:
        base_s = s[s.index <= start]
    else:
        base_s = s[s.index < a]
    end_s = s[s.index <= b]
    if not len(base_s) or not len(end_s): return np.nan
    return end_s.iloc[-1] / base_s.iloc[-1] - 1


def main():
    ap = argparse.ArgumentParser(); ap.add_argument("--month")
    a = ap.parse_args()
    m = a.month or str((pd.Timestamp.today().to_period("M") - 1))
    m0, m1 = month_bounds(m)
    days = sorted(pd.Timestamp(os.path.basename(f)[:8]) for f in glob.glob("data/bhav/raw/*.zip"))
    tdays = [d for d in days if m0 <= d <= m1]
    ix = pd.read_csv("data/indices/closes.csv", index_col=0, parse_dates=True) if os.path.exists("data/indices/closes.csv") else pd.DataFrame()
    fleet = json.load(open("paper/fleet.json"))["accounts"]
    L = [f"# Monthly review: {m}\n", f"_Numbers generated by monthly_review.py; read-only. Trading days with an NSE price file this month: {len(tdays)}._\n"]

    # 1. running and integrity
    L.append("## 1. Is it running?\n\n| Account | Days recorded / expected | Missing days | Integrity |\n|---|---|---|---|")
    try:
        from alpha.bhav_panel import build
        import check_integrity
        raw_c = build()["raw_close"]
    except Exception as e:
        raw_c = None; L.insert(2, f"_Integrity check could not run: {e}_\n")
    rows = {}
    for acc in fleet:
        o = acc["out"]
        if not os.path.exists(f"{o}/nav.csv"):
            L.append(f"| {o} | not started | | |"); continue
        nav = pd.read_csv(f"{o}/nav.csv", parse_dates=["date"]).set_index("date")
        first = nav.index[0]
        exp = [d for d in tdays if d >= first]
        rec = [d for d in exp if d in nav.index]
        miss = [str(d.date()) for d in exp if d not in nav.index]
        integ = "n/a"
        if raw_c is not None:
            p = check_integrity.check(o, raw_c); integ = "OK" if not p else "PROBLEMS: " + "; ".join(p[:3])
        L.append(f"| {o} | {len(rec)} / {len(exp)} | {', '.join(miss) if miss else 'none'} | {integ} |")
        rows[o] = nav

    # 2. results
    L.append("\n## 2. Results (post-tax NAV; benchmarks are price indices)\n\n| Account | Month | Nifty 50 month | vs Nifty 50 | Since start | Nifty 500 since start | vs Nifty 500 | Max drawdown since start | Fills in month |\n|---|---|---|---|---|---|---|---|---|")
    for o, nav in rows.items():
        s = nav["nav_post_tax"]; mm = s[(s.index >= m0) & (s.index <= m1)]
        before = s[s.index < m0]
        r_m = mm.iloc[-1] / (before.iloc[-1] if len(before) else s.iloc[0]) - 1 if len(mm) else np.nan   # from its first NAV if it started this month
        r_all = s.iloc[-1] / s.iloc[0] - 1
        n50m = idx_ret(ix, "Nifty 50", m0, m1, start=s.index[0]) if len(ix) else np.nan
        n500 = (ix["Nifty 500"].dropna().loc[:s.index[-1]].iloc[-1] / ix["Nifty 500"].dropna().loc[:s.index[0]].iloc[-1] - 1) if len(ix) and len(ix["Nifty 500"].dropna().loc[:s.index[0]]) else np.nan
        dd = (s / s.cummax() - 1).min()
        fills = int(nav.loc[(nav.index >= m0) & (nav.index <= m1), "fills"].sum()) if "fills" in nav else 0
        f = lambda x: f"{x * 100:+.1f}%" if np.isfinite(x) else "n/a"
        L.append(f"| {o}{' (PRIMARY)' if o == PRIMARY else ''} | {f(r_m)} | {f(n50m)} | {f(r_m - n50m) if np.isfinite(r_m) and np.isfinite(n50m) else 'n/a'} | {f(r_all)} | {f(n500)} | "
                 f"{f(r_all - n500) if np.isfinite(n500) else 'n/a'} | {f(dd)} | {fills} |")

    # 3. primary vs pre-set verdicts
    L.append("\n## 3. Primary against the pre-set verdicts\n")
    if PRIMARY in rows:
        s = rows[PRIMARY]["nav_post_tax"]; age = (s.index[-1] - s.index[0]).days / 30.44
        dd = (s / s.cummax() - 1).min(); r_all = s.iloc[-1] / s.iloc[0] - 1
        n5 = ix["Nifty 500"].dropna() if len(ix) else pd.Series(dtype=float)
        gap = r_all - (n5.loc[:s.index[-1]].iloc[-1] / n5.loc[:s.index[0]].iloc[-1] - 1) if len(n5.loc[:s.index[0]]) else np.nan
        L.append(f"Age {age:.1f} months; post-tax return {r_all * 100:+.1f}%; gap to Nifty 500 {gap * 100:+.1f} points; max drawdown {dd * 100:.1f}%.\n")
        L.append("| Check | Threshold | Now | Status |\n|---|---|---|---|")
        L.append(f"| Broken (applies from 6 months) | drawdown worse than -40% | {dd * 100:.1f}% | {'BREACH' if dd < -0.40 else 'ok'}{'' if age >= 6 else ' (not yet applicable)'} |")
        L.append(f"| Broken (applies from 6 months) | trails Nifty 500 by more than 20 pts | {gap * 100:+.1f} pts | {'BREACH' if gap < -0.20 else 'ok'}{'' if age >= 6 else ' (not yet applicable)'} |")
        L.append(f"| 12-month verdict | working: ahead with drawdown better than -35%; broken: behind by more than 25 pts | {gap * 100:+.1f} pts, {dd * 100:.1f}% | {'pending' if age < 12 else ('working' if gap > 0 and dd > -0.35 else ('broken' if gap < -0.25 else 'unclear but normal'))} |")
        L.append(f"\nNormal ranges from the stress tests (research/stress/RESULTS.md): behind the equal-weight universe in 15% of 12-month windows (once by 25 pts); "
                 f"falls of 25-32% happened three times since 2012.")
    else:
        L.append("Primary not started yet.")

    # 4. post-trade
    L.append("\n## 4. Post-trade (primary)\n")
    cf = f"{PRIMARY}/trades/cases.csv"
    if os.path.exists(cf) and os.path.getsize(cf) > 5:
        C = pd.read_csv(cf); C["exit"] = pd.to_datetime(C["exit"]); Cm = C[(C["exit"] >= m0) & (C["exit"] <= m1)]
        L.append(f"Closed this month: {len(Cm)}; all closed trades so far: {len(C)}.")
        if len(Cm): L.append("Diagnoses this month: " + ", ".join(f"{k} {v}" for k, v in Cm["diagnosis"].value_counts().items()) + ".")
        lf = f"{PRIMARY}/trades/LEARNINGS.md"
        if os.path.exists(lf):
            t = open(lf).read(); seg = t.split("## Candidate hypotheses")[-1].strip().splitlines()[1:4]
            L.append("Candidate hypotheses: " + (" ".join(x.strip() for x in seg if x.strip()) or "none"))
    else:
        L.append("No closed trades yet.")
    os.makedirs("reports/monthly", exist_ok=True)
    out = f"reports/monthly/{m}.md"; open(out, "w").write("\n".join(L) + "\n")
    print("\n".join(L)); print(f"\nwritten {out}")


if __name__ == "__main__":
    main()
